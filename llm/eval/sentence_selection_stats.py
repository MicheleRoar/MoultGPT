#!/usr/bin/env python3
# llm/eval/sentence_selection_stats.py
"""
Real, executed statistics for the paper's "Sentence Selection Behaviour"
placeholder: how many sentences does a paper start with, how many survive
ontology-based filtering, and how many are finally selected by TF-IDF/
K-Means clustering (pipeline/summarization.py:extract_relevant_sentences)?

No network access needed: runs against the 21 real papers already parsed
to llm/finetuning/papers/*.tei.xml (pipeline.parser.tei_to_text).

This intentionally duplicates the sentence-splitting and ontology-scoring
steps from pipeline/summarization.py rather than modifying that module to
expose intermediate counts -- extract_relevant_sentences() is the
production function used by the live API and compare_models.py, and
changing its return type/signature to serve this one-off stats script is
not worth the risk of the two silently diverging. Keeping this script's
logic in lockstep with summarization.py's actual filtering means: if you
change num_sentences/min_total_score there, re-run this script with the
same arguments.

Usage
-----
    cd llm
    python eval/sentence_selection_stats.py --out eval/sentence_selection_stats.md
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from statistics import mean, median

EVAL_ROOT = Path(__file__).resolve().parent
LLM_ROOT = EVAL_ROOT.parent
if str(LLM_ROOT) not in sys.path:
    sys.path.insert(0, str(LLM_ROOT))

from pipeline.parser import tei_to_text  # type: ignore  # noqa: E402
from pipeline.summarization import (  # type: ignore  # noqa: E402
    _simple_sentence_split,
    _ontology_sentence_signal,
    extract_relevant_sentences,
)
from domain.moulting_ontology_gate import MoultingOntologyGate  # type: ignore  # noqa: E402

DEFAULT_PAPERS_DIR = LLM_ROOT / "finetuning" / "papers"
DEFAULT_OWL_PATH = LLM_ROOT / "data" / "moultdb_moulting_ontology_v3_8.owl"
NUM_SUMMARY_SENTENCES = 20  # same default as pipeline/domain_pipeline.py
MIN_TOTAL_SCORE = 2.5


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--papers_dir", type=str, default=str(DEFAULT_PAPERS_DIR))
    parser.add_argument("--ontology_owl", type=str, default=str(DEFAULT_OWL_PATH))
    parser.add_argument("--out", type=str, default=str(EVAL_ROOT / "sentence_selection_stats.md"))
    args = parser.parse_args()

    papers_dir = Path(args.papers_dir)
    tei_files = sorted(papers_dir.glob("*.tei.xml"), key=lambda p: int(p.stem.split(".")[0]))
    print(f"[INFO] Found {len(tei_files)} papers in {papers_dir}.")

    gate = MoultingOntologyGate(owl_path=args.ontology_owl)

    rows = []
    for tei_path in tei_files:
        paper_id = tei_path.stem.split(".")[0]
        full_text = tei_to_text(str(tei_path))
        if not full_text.strip():
            print(f"[WARN] Empty text for paper {paper_id}, skipping.")
            continue

        all_sentences = [s.strip() for s in _simple_sentence_split(full_text) if s.strip()]
        n_original = len(all_sentences)

        n_ontology_filtered = 0
        for sent in all_sentences:
            signal = _ontology_sentence_signal(sentence=sent, ontology_gate=gate, min_total_score=MIN_TOTAL_SCORE)
            if signal["allow"]:
                n_ontology_filtered += 1

        summary = extract_relevant_sentences(
            full_text=full_text,
            ontology_gate=gate,
            num_sentences=NUM_SUMMARY_SENTENCES,
            min_total_score=MIN_TOTAL_SCORE,
        )
        n_selected = len([s for s in summary.split("\n") if s.strip()])

        pct_reduction = 100.0 * (1 - n_selected / n_original) if n_original else 0.0
        rows.append({
            "paper_id": paper_id, "n_original": n_original,
            "n_ontology_filtered": n_ontology_filtered, "n_selected": n_selected,
            "pct_reduction": pct_reduction,
        })
        print(f"  paper {paper_id}: {n_original} -> {n_ontology_filtered} (ontology) -> {n_selected} (final), "
              f"{pct_reduction:.1f}% reduction")

    if not rows:
        print("[ERROR] No papers processed, nothing to report.")
        return

    lines = []
    lines.append("# Sentence selection — real statistics across the 21-paper corpus\n")
    lines.append(
        f"Generated by `sentence_selection_stats.py`. Corpus: `llm/finetuning/papers/*.tei.xml` "
        f"({len(rows)} papers with extractable text). Uses the production ontology-gate scoring "
        f"(`pipeline/summarization.py`) with the same defaults as `pipeline/domain_pipeline.py` "
        f"(`num_sentences={NUM_SUMMARY_SENTENCES}`, `min_total_score={MIN_TOTAL_SCORE}`).\n"
    )
    lines.append("## Per-paper\n")
    lines.append("| Paper | Original sentences | After ontology filter | Final selected | % reduction |")
    lines.append("|---|---|---|---|---|")
    for r in rows:
        lines.append(f"| {r['paper_id']} | {r['n_original']} | {r['n_ontology_filtered']} | "
                     f"{r['n_selected']} | {r['pct_reduction']:.1f}% |")

    orig = [r["n_original"] for r in rows]
    filt = [r["n_ontology_filtered"] for r in rows]
    sel = [r["n_selected"] for r in rows]
    pct = [r["pct_reduction"] for r in rows]

    lines.append("\n## Aggregate\n")
    lines.append("| | mean | median | min | max |")
    lines.append("|---|---|---|---|---|")
    lines.append(f"| Original sentences | {mean(orig):.1f} | {median(orig):.1f} | {min(orig)} | {max(orig)} |")
    lines.append(f"| After ontology filter | {mean(filt):.1f} | {median(filt):.1f} | {min(filt)} | {max(filt)} |")
    lines.append(f"| Final selected | {mean(sel):.1f} | {median(sel):.1f} | {min(sel)} | {max(sel)} |")
    lines.append(f"| % reduction (original -> final) | {mean(pct):.1f}% | {median(pct):.1f}% | {min(pct):.1f}% | {max(pct):.1f}% |")

    n_capped = sum(1 for r in rows if r["n_ontology_filtered"] > NUM_SUMMARY_SENTENCES)
    lines.append(
        f"\n{n_capped}/{len(rows)} papers had more ontology-filtered sentences than the "
        f"`num_sentences={NUM_SUMMARY_SENTENCES}` cap, meaning TF-IDF/K-Means clustering actually "
        f"performed a further reduction for them; for the rest, all ontology-filtered sentences were "
        f"kept as-is (fewer candidates than the cap, no clustering reduction needed).\n"
    )

    out_path = Path(args.out)
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\n[DONE] Wrote {out_path}")


if __name__ == "__main__":
    main()
